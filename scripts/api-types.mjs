#!/usr/bin/env node
// Generate packages/sdk/src/api.gen.ts from contracts/api-v1.schema.json, the JSON
// Schema of crates/miy/src/api_contract.rs. `--check` fails when the committed file
// differs, so the SDK and platform types cannot drift from the Rust responses.
// Covers the schema forms the contract uses: objects, arrays, nullable types, string
// enums and constants, and $defs references.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "contracts/api-v1.schema.json");
const outputPath = join(root, "packages/sdk/src/api.gen.ts");

function literal(value) {
  return JSON.stringify(value);
}

function union(types) {
  return [...new Set(types)].join(" | ");
}

function typeOf(schema, where) {
  if (schema.$ref) {
    const prefix = "#/$defs/";
    if (!schema.$ref.startsWith(prefix)) throw new Error(`${where}: unsupported $ref ${schema.$ref}`);
    return schema.$ref.slice(prefix.length);
  }
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return union(schema.enum.map(literal));
  for (const key of ["anyOf", "oneOf"]) {
    if (schema[key]) return union(schema[key].map((part, index) => typeOf(part, `${where}.${key}[${index}]`)));
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  return union(
    types.map((type) => {
      switch (type) {
        case "string":
          return "string";
        case "integer":
        case "number":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array": {
          const item = typeOf(schema.items ?? {}, `${where}.items`);
          return item.includes(" | ") ? `(${item})[]` : `${item}[]`;
        }
        default:
          throw new Error(`${where}: unsupported type ${JSON.stringify(type)}`);
      }
    }),
  );
}

function comment(text, indent) {
  if (!text) return "";
  const lines = text.split("\n");
  if (lines.length === 1) return `${indent}/** ${text} */\n`;
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

export function generate(schema) {
  const parts = [
    "// Generated by scripts/api-types.mjs from contracts/api-v1.schema.json; do not edit.\n",
    "// The source is crates/miy/src/api_contract.rs.\n",
  ];
  for (const name of Object.keys(schema.$defs).sort()) {
    const definition = schema.$defs[name];
    parts.push("\n");
    parts.push(comment(definition.description, ""));
    if (definition.type === "object" && definition.properties) {
      const required = new Set(definition.required ?? []);
      parts.push(`export interface ${name} {\n`);
      for (const [property, value] of Object.entries(definition.properties)) {
        parts.push(comment(value.description, "  "));
        const optional = required.has(property) ? "" : "?";
        parts.push(`  ${property}${optional}: ${typeOf(value, `${name}.${property}`)};\n`);
      }
      parts.push("}\n");
    } else {
      parts.push(`export type ${name} = ${typeOf(definition, name)};\n`);
    }
  }
  return parts.join("");
}

function main() {
  const generated = generate(JSON.parse(readFileSync(schemaPath, "utf8")));
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(outputPath, "utf8");
    } catch {
      // A missing file is stale too.
    }
    if (committed !== generated) {
      console.error("packages/sdk/src/api.gen.ts is stale: run node scripts/api-types.mjs");
      process.exit(1);
    }
    console.log("PASS api types match contracts/api-v1.schema.json");
    return;
  }
  writeFileSync(outputPath, generated);
  console.log(`wrote ${outputPath}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
