#!/usr/bin/env node
// Generate workspace and app SDK types from contracts/api-v1.schema.json, the JSON
// Schema of crates/miy/src/api_contract.rs. `--check` fails when the committed file
// differs, so the SDK and platform types cannot drift from the Rust responses.
// Covers the schema forms the contract uses: objects, arrays, nullable types, string
// enums and constants, and $defs references.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = join(root, "contracts/api-v1.schema.json");
const outputs = [
  { path: "packages/sdk/src/api.gen.ts" },
  { path: "templates/rust-react/sdk/browser/api.gen.ts", roots: ["DirectoryPage", "StoredFile", "ReserveFile", "AttachFile"] },
];

// App bundles receive only their public contract and its referenced definitions,
// rather than the platform's administrator and deployment response inventory.
export function selectDefinitions(schema, roots) {
  const selected = new Set();
  function visit(name) {
    if (selected.has(name)) return;
    const definition = schema.$defs[name];
    if (!definition) throw new Error(`Unknown contract type: ${name}`);
    selected.add(name);
    function scan(value) {
      if (!value || typeof value !== "object") return;
      if (typeof value.$ref === "string") {
        if (!value.$ref.startsWith("#/$defs/"))
          throw new Error(`Unsupported contract reference: ${value.$ref}`);
        visit(value.$ref.slice("#/$defs/".length));
      }
      for (const child of Object.values(value)) scan(child);
    }
    scan(definition);
  }
  for (const name of roots) visit(name);
  return { ...schema, $defs: Object.fromEntries([...selected].sort().map(name => [name, schema.$defs[name]])) };
}

function literal(value) {
  return JSON.stringify(value);
}

function union(types) {
  return [...new Set(types)].join(" | ");
}

function typeOf(schema, where) {
  if (schema.$ref) {
    const prefix = "#/$defs/";
    if (!schema.$ref.startsWith(prefix)) throw new Error(`${where}: unsupported $ref ${schema.$ref}`);
    return schema.$ref.slice(prefix.length);
  }
  if (schema.const !== undefined) return literal(schema.const);
  if (schema.enum) return union(schema.enum.map(literal));
  for (const key of ["anyOf", "oneOf"]) {
    if (schema[key]) return union(schema[key].map((part, index) => typeOf(part, `${where}.${key}[${index}]`)));
  }
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  return union(
    types.map((type) => {
      switch (type) {
        case "string":
          return "string";
        case "integer":
        case "number":
          return "number";
        case "boolean":
          return "boolean";
        case "null":
          return "null";
        case "array": {
          const item = typeOf(schema.items ?? {}, `${where}.items`);
          return item.includes(" | ") ? `(${item})[]` : `${item}[]`;
        }
        default:
          throw new Error(`${where}: unsupported type ${JSON.stringify(type)}`);
      }
    }),
  );
}

function comment(text, indent) {
  if (!text) return "";
  const lines = text.split("\n");
  if (lines.length === 1) return `${indent}/** ${text} */\n`;
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

export function generate(schema) {
  const parts = [
    "// Generated by scripts/api-types.mjs from contracts/api-v1.schema.json; do not edit.\n",
    "// The source is crates/miy/src/api_contract.rs.\n",
  ];
  for (const name of Object.keys(schema.$defs).sort()) {
    const definition = schema.$defs[name];
    parts.push("\n");
    parts.push(comment(definition.description, ""));
    if (definition.type === "object" && definition.properties) {
      const required = new Set(definition.required ?? []);
      parts.push(`export interface ${name} {\n`);
      for (const [property, value] of Object.entries(definition.properties)) {
        parts.push(comment(value.description, "  "));
        const optional = required.has(property) ? "" : "?";
        parts.push(`  ${property}${optional}: ${typeOf(value, `${name}.${property}`)};\n`);
      }
      parts.push("}\n");
    } else {
      parts.push(`export type ${name} = ${typeOf(definition, name)};\n`);
    }
  }
  return parts.join("");
}

function main() {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  const check = process.argv.includes("--check");
  let stale = false;
  for (const output of outputs) {
    const generated = generate(output.roots ? selectDefinitions(schema, output.roots) : schema);
    const outputPath = join(root, output.path);
    if (check) {
      let committed = "";
      try {
        committed = readFileSync(outputPath, "utf8");
      } catch {
        // A missing file is stale too.
      }
      if (committed !== generated) {
        console.error(`${output.path} is stale: run node scripts/api-types.mjs`);
        stale = true;
      }
    } else {
      writeFileSync(outputPath, generated);
      console.log(`wrote ${outputPath}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log("PASS workspace and app SDK types match contracts/api-v1.schema.json");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
