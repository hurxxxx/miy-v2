"""Regenerate src/error_catalog.rs from AI-DO's server message catalog.

The backend answers `{"error":{"code","message"}}`; `message` is AI-DO's
English catalog text for the code (the UI translates the code itself). This
copies the English messages of every code the PMS backend raises.

    python3 -I scripts/gen-error-catalog.py \
        ../../../ai-do/prod/apps/api/src/ai_do_api/core/i18n_catalog.py \
        src/error_catalog.rs
"""
import ast
import sys
from pathlib import Path

source = Path(sys.argv[1]).read_text(encoding="utf-8")
out = Path(sys.argv[2])
tree = ast.parse(source)
messages = None
for node in tree.body:
    target = getattr(node, "target", None) or (node.targets[0] if isinstance(node, ast.Assign) else None)
    if isinstance(target, ast.Name) and target.id == "MESSAGES":
        messages = ast.literal_eval(node.value)
assert messages, "MESSAGES not found"
EXTRA = ["auth.user_not_found", "platform.app_access_required", "validation.request_invalid"]
codes = sorted(code for code in messages if code.startswith("pms.")) + EXTRA
import json

def rust_str(value):
    return json.dumps(value, ensure_ascii=False)

lines = [
    "// Generated by scripts/gen-error-catalog.py from AI-DO",
    "// apps/api/src/ai_do_api/core/i18n_catalog.py at 0002af062 (en-US texts).",
    "/// AI-DO's English message for a dotted error code.",
    "pub fn message(code: &str) -> Option<&'static str> {",
    "    Some(match code {",
]
for code in codes:
    lines.append(f"        {rust_str(code)} => {rust_str(messages[code]['en-US'])},")
lines += ["        _ => return None,", "    })", "}", ""]
out.write_text("\n".join(lines), encoding="utf-8")
print("wrote", out, len(codes), "codes")
