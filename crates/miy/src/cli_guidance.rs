pub fn command_reference() -> String {
    let help = crate::agent_tools::cli_help();
    let mut out = format!(
        "# MIY CLI command reference\n\nGenerated from MIY CLI {VERSION}, SDK bundle {}. Do not edit this generated file.\n\n",
        crate::bundle::VERSION
    );
    for row in help["commands"].as_array().unwrap() {
        out.push_str(&format!(
            "## {}\n\n```text\n{}```\n\n",
            row["command"].as_str().unwrap(),
            row["help"].as_str().unwrap()
        ));
    }
    out
}
pub fn manual() -> String {
    format!(
        "# MIY CLI manual\n\nCLI {VERSION} / SDK bundle {}. Generated by app init/setup/upgrade.\n\n{}\n\n{}",
        crate::bundle::VERSION,
        WORKFLOW.replace(
            "[command reference](commands.md)",
            "command reference below"
        ),
        command_reference()
    )
}
fn files() -> BTreeMap<String, String> {
    let mut files = BTreeMap::from([
        ("docs/CLI-REFERENCE.md".into(), manual()),
        (".gitattributes".into(), GIT_ATTRIBUTES.into()),
    ]);
    let skill = format!(
        "{SKILL}\nInstalled CLI: {VERSION}. SDK bundle: {}.\n",
        crate::bundle::VERSION
    );
    let commands = command_reference();
    for client in [".agents", ".claude"] {
        let root = format!("{client}/skills/miy-cli");
        files.insert(format!("{root}/SKILL.md"), skill.clone());
        files.insert(format!("{root}/references/workflow.md"), WORKFLOW.into());
        files.insert(format!("{root}/references/commands.md"), commands.clone());
    }
    files
}
#[derive(Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Lock {
    protocol: String,
    cli_version: String,
    bundle_version: String,
    files: BTreeMap<String, String>,
}
fn expected(files: &BTreeMap<String, String>) -> Lock {
    Lock {
        protocol: PROTOCOL.into(),
        cli_version: VERSION.into(),
        bundle_version: crate::bundle::VERSION.into(),
        files: files
            .iter()
            .map(|(p, c)| (p.clone(), crate::contract::hash(c)))
            .collect(),
    }
}
// Never follow project-owned symlinks into another project or global agent directory.
pub(crate) fn safe_target(root: &Path, relative: &str) -> Result<()> {
    let mut path = root.to_path_buf();
    let parts: Vec<_> = Path::new(relative).components().collect();
    for (index, part) in parts.iter().enumerate() {
        path.push(part);
        crate::platform::reject_reparse(&path)?;
        match std::fs::symlink_metadata(&path) {
            Ok(meta) => ensure!(
                if index + 1 == parts.len() {
                    meta.is_file()
                } else {
                    meta.is_dir()
                },
                "cli_guidance_path_conflict: {relative}"
            ),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => return Err(e.into()),
        }
    }
    Ok(())
}
fn load(root: &Path) -> Result<Option<Lock>> {
    safe_target(root, LOCK)?;
    match std::fs::read(root.join(LOCK)) {
        Ok(bytes) => {
            let lock: Lock = serde_json::from_slice(&bytes).context("invalid_cli_guidance_lock")?;
            ensure!(
                lock.protocol == PROTOCOL,
                "unsupported_cli_guidance_protocol"
            );
            Ok(Some(lock))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}
pub fn preflight(root: &Path) -> Result<()> {
    let files = files();
    let old = load(root)?;
    if let Some(old) = &old {
        ensure!(
            old.files.keys().all(|p| files.contains_key(p)),
            "unsupported_cli_guidance_paths"
        );
    }
    for (path, content) in &files {
        safe_target(root, path)?;
        if let Ok(actual) = std::fs::read(root.join(path)) {
            let hash = crate::contract::hash(&actual);
            ensure!(
                actual == content.as_bytes()
                    || old.as_ref().and_then(|v| v.files.get(path)) == Some(&hash),
                "cli_guidance_modified_or_conflict: {path}; preserve custom notes separately before app setup"
            );
        }
    }
    Ok(())
}
fn atomic_write(path: &Path, contents: &[u8]) -> Result<()> {
    crate::platform::atomic_write(path, contents)
}
pub fn sync(root: &Path) -> Result<Value> {
    preflight(root)?;
    let files = files();
    for (path, content) in &files {
        atomic_write(&root.join(path), content.as_bytes())?;
    }
    // Write last. A partial update can be safely retried: preflight accepts both old and new content.
    atomic_write(
        &root.join(LOCK),
        &serde_json::to_vec_pretty(&expected(&files))?,
    )?;
    verify(root)
}
pub fn verify(root: &Path) -> Result<Value> {
    let lock =
        load(root)?.context("cli_guidance_missing: run the compatible global miy app setup")?;
    let files = files();
    let expected = expected(&files);
    ensure!(
        lock.cli_version == expected.cli_version
            && lock.bundle_version == expected.bundle_version
            && lock.files == expected.files,
        "cli_guidance_version_mismatch: run the intended CLI's app setup to sync executable, skills and manual"
    );
    for (path, hash) in &expected.files {
        safe_target(root, path)?;
        ensure!(
            crate::contract::hash(
                std::fs::read(root.join(path))
                    .with_context(|| format!("cli_guidance_missing: {path}; run app setup"))?
            ) == *hash,
            "cli_guidance_modified: {path}"
        );
    }
    Ok(
        json!({"valid":true,"cliVersion":VERSION,"bundleVersion":crate::bundle::VERSION,"skills":[".agents/skills/miy-cli",".claude/skills/miy-cli"],"manual":"docs/CLI-REFERENCE.md","lock":LOCK}),
    )
}
pub fn operation(root: &Path) -> Result<std::fs::File> {
    safe_target(root, ".miy/cli-setup.lock")?;
    std::fs::create_dir_all(root.join(".miy"))?;
    let lock = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .create(true)
        .truncate(false)
        .open(root.join(".miy/cli-setup.lock"))?;
    lock.try_lock()
        .context("cli_setup_already_running_for_this_project")?;
    Ok(lock)
}
pub fn install_binary(root: &Path) -> Result<()> {
    safe_target(root, crate::platform::project_cli_relative())?;
    crate::platform::install_executable(
        &std::env::current_exe()?,
        &crate::platform::project_cli(root),
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn line_endings_are_managed_without_overwriting_custom_attributes() {
        let root = tempfile::tempdir().unwrap();
        let path = root.path().join(".gitattributes");
        std::fs::write(&path, "custom attributes\n").unwrap();
        assert!(preflight(root.path()).is_err());
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "custom attributes\n"
        );
        std::fs::remove_file(&path).unwrap();
        sync(root.path()).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), GIT_ATTRIBUTES);
        assert!(
            load(root.path())
                .unwrap()
                .unwrap()
                .files
                .contains_key(".gitattributes")
        );
    }
    #[test]
    fn guidance_update_checks_integrity_and_recovers_partial_writes() {
        let root = tempfile::tempdir().unwrap();
        sync(root.path()).unwrap();
        let mut old = load(root.path()).unwrap().unwrap();
        let path = "docs/CLI-REFERENCE.md";
        std::fs::write(root.path().join(path), "old generated manual").unwrap();
        old.cli_version = "0.4.0".into();
        old.files
            .insert(path.into(), crate::contract::hash("old generated manual"));
        std::fs::write(root.path().join(LOCK), serde_json::to_vec(&old).unwrap()).unwrap();
        assert!(verify(root.path()).is_err());
        // Some files already have the new content; another is missing after interruption.
        std::fs::remove_file(
            root.path()
                .join(".claude/skills/miy-cli/references/commands.md"),
        )
        .unwrap();
        sync(root.path()).unwrap();
        std::fs::write(root.path().join(path), "user notes").unwrap();
        assert!(sync(root.path()).is_err());
        assert_eq!(
            std::fs::read_to_string(root.path().join(path)).unwrap(),
            "user notes"
        );
    }
    #[test]
    fn generated_command_reference_matches_clap_and_both_agent_clients() {
        let files = files();
        let reference = command_reference();
        let help = crate::agent_tools::cli_help();
        for command in help["commands"].as_array().unwrap() {
            assert!(reference.contains(command["help"].as_str().unwrap()));
        }
        assert_eq!(
            files[".agents/skills/miy-cli/SKILL.md"],
            files[".claude/skills/miy-cli/SKILL.md"]
        );
        assert_eq!(
            files[".agents/skills/miy-cli/references/commands.md"],
            reference
        );
        assert!(files["docs/CLI-REFERENCE.md"].contains(&reference));
    }
    #[test]
    fn setup_is_serialized_per_project() {
        let root = tempfile::tempdir().unwrap();
        let first = operation(root.path()).unwrap();
        assert!(operation(root.path()).is_err());
        drop(first);
        assert!(operation(root.path()).is_ok());
    }
    #[cfg(unix)]
    #[test]
    fn guidance_never_overwrites_unmanaged_files_or_follows_symlinks() {
        let root = tempfile::tempdir().unwrap();
        let elsewhere = tempfile::tempdir().unwrap();
        std::os::unix::fs::symlink(elsewhere.path(), root.path().join(".agents")).unwrap();
        assert!(sync(root.path()).is_err());
        assert_eq!(std::fs::read_dir(elsewhere.path()).unwrap().count(), 0);
    }
}
